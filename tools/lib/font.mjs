export const FONT_H = 5;
export const glyph = (ch) => FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT['?'];

// ширина текста в px: глифы по S px на клетку + gap px между буквами
export const textWidth = (text, S, gap) => { const chars = [...text]; return chars.reduce((a, ch) => a + glyph(ch)[0].length * S, 0) + gap * Math.max(0, chars.length - 1); };

// рисует текст с левым верхним углом (x, y); возвращает ширину
export function drawText(c, text, x, y, S, gap, col) {
  for (const ch of text) {
    const g = glyph(ch);
    g.forEach((row, j) => [...row].forEach((v, i) => { if (v === '#') c.rect(x + i * S, y + j * S, S, S, col); }));
    x += g[0].length * S + gap;
  }
}

